export const getListingsByCategory = (categoryId: string): Listing[] => {
  return mockListings.filter((l) => l.category === categoryId);
};

export const getFeaturedListings = (): Listing[] => {
  return mockListings.filter((l) => l.isFeatured || l.isPromoted);
};

export const getListingById = (id: string): Listing | undefined => {
  return mockListings.find((l) => l.id === id);
};

export const getListingsByCity = (city: string): Listing[] => {
  return mockListings.filter((l) => l.city === city);
};

export const searchListings = (query: string): Listing[] => {
  const lower = query.toLowerCase();
  return mockListings.filter(
    (l) =>
      l.title.toLowerCase().includes(lower) ||
      l.description.toLowerCase().includes(lower) ||
      l.subcategory.toLowerCase().includes(lower) ||
      l.city.toLowerCase().includes(lower)
  );
};
